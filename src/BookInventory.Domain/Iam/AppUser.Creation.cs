using BookInventory.BuildingBlocks.Domain.Exceptions;

namespace BookInventory.Domain.Iam;

/// <summary>The identity and credentials every new account starts with; the password is already hashed.</summary>
public sealed record UserDraft(string FullName, string UserName, string? Email, string? Mobile, string PasswordHash);

public partial class AppUser
{
    /// <summary>Everything that differs between the ways an account can come into existence.</summary>
    private sealed record NewAccount(
        UserDraft Draft,
        Role Role,
        AccountStatus Status,
        bool MustChangePassword,
        bool IsSystemAccount,
        Guid ActorId,
        Guid? CompanyId = null);

    /// <summary>
    /// R2: staff accounts exist only because a Super Admin made them, they are immediately <see cref="AccountStatus.Active"/>
    /// and their first login must change the password.
    /// </summary>
    public static AppUser CreateStaff(UserDraft draft, Role role, Guid actorId, DateTime utcNow)
    {
        if (!role.IsStaff())
            throw new ValidationFailureException(IamMessages.UserRoleNotStaff);

        return Create(new NewAccount(draft, role, AccountStatus.Active, MustChangePassword: true, IsSystemAccount: false, actorId), utcNow);
    }

    /// <summary>
    /// R53: the hand-off from agent registration. The user id (username) was generated by the registering module.
    /// With <c>ApprovalRequired</c> the account waits as <see cref="AccountStatus.Pending"/>; with <c>InstantLogin</c> it
    /// is active straight away and the password the agent just chose is kept (no forced change).
    /// </summary>
    public static AppUser RegisterMember(UserDraft draft, bool activeImmediately, Guid actorId, DateTime utcNow)
    {
        if (string.IsNullOrWhiteSpace(draft.Email))
            throw new ValidationFailureException(IamMessages.UserEmailRequired);
        if (string.IsNullOrWhiteSpace(draft.Mobile))
            throw new ValidationFailureException(IamMessages.UserMobileRequired);

        return Create(
            new NewAccount(
                draft,
                Role.Member,
                activeImmediately ? AccountStatus.Active : AccountStatus.Pending,
                MustChangePassword: !activeImmediately,
                IsSystemAccount: false,
                actorId),
            utcNow);
    }

    /// <summary>
    /// R42/R51: the single hidden built-in Super Admin, created only by a startup seeder from configuration or a secret
    /// store. It authorizes exactly like a Super Admin but is invisible everywhere (R43) and never gets a forced
    /// password change (R45). This is the only place <see cref="IsSystemAccount"/> is ever set to true, and the only
    /// place a reserved user name such as <c>system</c> may be used.
    /// </summary>
    public static AppUser CreateSystemAccount(UserDraft draft, DateTime utcNow) =>
        Create(
            new NewAccount(draft, Role.SuperAdmin, AccountStatus.Active, MustChangePassword: false, IsSystemAccount: true, ActorId: Guid.Empty),
            utcNow);

    /// <summary>
    /// R51: the seeder replaces the stored password hash when the configured secret is rotated and the process restarts.
    /// The only way to touch the system account after it exists.
    /// </summary>
    public void RefreshSystemAccountCredentials(string passwordHash, string? email, string? mobile, DateTime utcNow)
    {
        EnsureSystemAccount();

        PasswordHash = RequirePasswordHash(passwordHash);
        PasswordChangedAt = utcNow;
        Email = NormalizeEmail(email);
        Mobile = NormalizeMobile(mobile);
    }

    private static AppUser Create(NewAccount account, DateTime utcNow) =>
        new()
        {
            UserName = RequireUserName(account.Draft.UserName, allowReserved: account.IsSystemAccount),
            Email = NormalizeEmail(account.Draft.Email),
            Mobile = NormalizeMobile(account.Draft.Mobile),
            FullName = RequireFullName(account.Draft.FullName),
            PasswordHash = RequirePasswordHash(account.Draft.PasswordHash),
            Role = account.Role,
            Status = account.Status,
            StatusChangedAt = utcNow,
            StatusChangedBy = account.ActorId == Guid.Empty ? null : account.ActorId,
            MustChangePassword = account.MustChangePassword,
            IsSystemAccount = account.IsSystemAccount,
            CompanyId = account.CompanyId
        };
}
